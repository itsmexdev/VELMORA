// ---------- Data access helpers ----------

export function getAllProducts(): Product[] {
  return products;
}

export function getProductBySlug(slug: string): Product | undefined {
  return products.find((p) => p.slug === slug);
}

export function getProductsByCategory(category: CategorySlug): Product[] {
  return products.filter((p) => p.category === category);
}

export type FlagKey = "newArrival" | "bestseller" | "rareFind" | "featured" | "limitedEdition";

export function getProductsByFlag(flag: FlagKey): Product[] {
  return products.filter((p) => Boolean(p[flag]));
}

export function getRelatedProducts(product: Product, count = 4): Product[] {
  const related = product.relatedSlugs
    .map((slug) => getProductBySlug(slug))
    .filter((p): p is Product => Boolean(p));
  if (related.length >= count) return related.slice(0, count);
  const fallback = getProductsByCategory(product.category).filter(
    (p) => p.slug !== product.slug && !related.includes(p)
  );
  return [...related, ...fallback].slice(0, count);
}

export function searchProducts(query: string): Product[] {
  const q = query.trim().toLowerCase();
  if (!q) return [];
  return products.filter((p) => {
    const haystack = [
      p.name,
      p.shortDescription,
      p.description,
      p.category,
      p.sku,
      ...p.tags,
    ]
      .join(" ")
      .toLowerCase();
    return haystack.includes(q);
  });
}

export function getAllTags(): string[] {
  const set = new Set<string>();
  products.forEach((p) => p.tags.forEach((t) => set.add(t)));
  return Array.from(set).sort();
}

export function getAllColors(scope: Product[] = products): string[] {
  const set = new Set<string>();
  scope.forEach((p) => p.colors?.forEach((c) => set.add(c)));
  return Array.from(set).sort();
}

export function priceBounds(scope: Product[] = products): { min: number; max: number } {
  if (scope.length === 0) return { min: 0, max: 0 };
  const prices = scope.map((p) => p.price);
  return { min: Math.floor(Math.min(...prices)), max: Math.ceil(Math.max(...prices)) };
}
